import { CheckCircle2, CircleHelp, Gavel, ListOrdered, Sparkles } from "lucide-react";
import type { ReactNode } from "react";
import { Markdown } from "@/components/common/markdown";
import type { MeetingReport } from "@/lib/api/types";
import { formatTimestamp } from "@/lib/format";
import { TopicChips } from "../topic-chips";

function Block({ icon: Icon, title, children }: { icon: typeof Sparkles; title: string; children: ReactNode }) {
  return (
    <section className="rounded-xl border bg-card p-5 shadow-xs sm:p-6">
      <h3 className="mb-4 flex items-center gap-2 text-sm font-semibold">
        <Icon className="size-4 text-primary" aria-hidden="true" />
        {title}
      </h3>
      {children}
    </section>
  );
}

export function SummaryTab({ report, onJumpTo }: { report: MeetingReport; onJumpTo?: (ms: number) => void }) {
  return (
    <div className="grid gap-5 lg:grid-cols-[minmax(0,1.6fr)_minmax(0,1fr)]">
      <div className="space-y-5">
        <Block icon={Sparkles} title="Summary">
          {report.summary ? <Markdown size="sm">{report.summary}</Markdown> : <p className="text-sm text-muted-foreground">No summary.</p>}
          {report.topics.length > 0 && <TopicChips topics={report.topics} max={8} className="mt-4" />}
        </Block>

        {report.chapters.length > 0 && (
          <Block icon={ListOrdered} title="Chapters">
            <ol className="relative space-y-5 border-l pl-6">
              {report.chapters.map((chapter, index) => (
                <li key={`${chapter.startMs}-${index}`} className="relative">
                  <span aria-hidden="true" className="absolute top-1.5 -left-[29px] size-2.5 rounded-full bg-primary ring-4 ring-card" />
                  <div className="flex flex-wrap items-center gap-2">
                    <button
                      type="button"
                      onClick={() => onJumpTo?.(chapter.startMs)}
                      disabled={!onJumpTo}
                      className="rounded-md bg-brand-soft px-1.5 py-0.5 font-mono text-xs text-brand-soft-foreground tabular-nums hover:underline disabled:no-underline"
                      aria-label={`Jump to ${formatTimestamp(chapter.startMs)} in the transcript`}
                    >
                      {formatTimestamp(chapter.startMs)}
                    </button>
                    <p className="text-sm font-medium">{chapter.title}</p>
                  </div>
                  <p className="mt-1 text-sm text-muted-foreground">{chapter.summary}</p>
                </li>
              ))}
            </ol>
          </Block>
        )}

        {report.keyQuestions.length > 0 && (
          <Block icon={CircleHelp} title="Key questions">
            <ul className="space-y-4">
              {report.keyQuestions.map((q, index) => (
                <li key={index} className="rounded-lg bg-muted/40 p-4">
                  <p className="text-sm font-medium">{q.question}</p>
                  {q.askedBy && <p className="mt-0.5 text-xs text-muted-foreground">Asked by {q.askedBy}</p>}
                  <p className={q.answer ? "mt-2 text-sm" : "mt-2 text-sm text-muted-foreground italic"}>
                    {q.answer ?? "No answer was given in the meeting."}
                  </p>
                </li>
              ))}
            </ul>
          </Block>
        )}
      </div>

      <div className="space-y-5">
        {report.keyPoints.length > 0 && (
          <Block icon={CheckCircle2} title="Key points">
            <ul className="space-y-2.5">
              {report.keyPoints.map((point, index) => (
                <li key={index} className="flex gap-2.5 text-sm">
                  <span aria-hidden="true" className="mt-2 size-1.5 shrink-0 rounded-full bg-primary" />
                  <span>{point}</span>
                </li>
              ))}
            </ul>
          </Block>
        )}
        <Block icon={Gavel} title="Decisions">
          {report.decisions.length > 0 ? (
            <ul className="space-y-2.5">
              {report.decisions.map((decision, index) => (
                <li key={index} className="flex gap-2.5 text-sm">
                  <CheckCircle2 className="mt-0.5 size-4 shrink-0 text-emerald-600 dark:text-emerald-400" aria-hidden="true" />
                  <span>{decision}</span>
                </li>
              ))}
            </ul>
          ) : (
            <p className="text-sm text-muted-foreground">No explicit decisions were recorded.</p>
          )}
        </Block>
        {report.model && <p className="px-1 text-xs text-muted-foreground">Generated by {report.model}</p>}
      </div>
    </div>
  );
}
